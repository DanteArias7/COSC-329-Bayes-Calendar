"""Week 10: compute the expected utility of each action for example students
and pick the best one. Writes the results to docs/week10_decision_results.md.

Run from the project root:
    python scripts/run_decision.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.decision import ACTIONS, DecisionMaker
from src.inference import marginal

STUDENTS = {
    "Struggling student, exam soon": {
        "Difficulty_A": "Hard", "Difficulty_B": "Hard", "Difficulty_C": "Medium",
        "PracticeScore": "Low", "DaysRemaining": "Few",
    },
    "Struggling student, lots of time": {
        "Difficulty_A": "Hard", "Difficulty_B": "Hard", "Difficulty_C": "Medium",
        "PracticeScore": "Low", "DaysRemaining": "Many",
    },
    "Average student, exam soon": {
        "Difficulty_A": "Medium", "Difficulty_B": "Medium", "Difficulty_C": "Medium",
        "PracticeScore": "Medium", "DaysRemaining": "Few",
    },
    "Average student, about a week left": {
        "Difficulty_A": "Medium", "Difficulty_B": "Medium", "Difficulty_C": "Medium",
        "PracticeScore": "Medium", "DaysRemaining": "Some",
    },
    "Advanced student, exam soon": {
        "Difficulty_A": "Easy", "Difficulty_B": "Easy", "Difficulty_C": "Medium",
        "PracticeScore": "High", "DaysRemaining": "Few",
    },
    "Advanced student, lots of time": {
        "Difficulty_A": "Easy", "Difficulty_B": "Easy", "Difficulty_C": "Easy",
        "PracticeScore": "High", "DaysRemaining": "Many",
    },
}


def pct(x):
    return f"{x * 100:.1f}%"


def main():
    dm = DecisionMaker()
    lines = ["# Week 10 Decision Results", "",
             "Generated by `scripts/run_decision.py`. Utility function and reasoning are in `utility.md`.", ""]
    summary = ["## Summary", "", "| Student | Best action | EU (Intense / Light / Rest) |", "|---|---|---|"]

    for name, ev in STUDENTS.items():
        r = dm.decide(ev)
        eu = r["expected_utility"]
        summary.append(f"| {name} | **{r['best_action']}** | "
                       f"{eu['Intense']:.1f} / {eu['Light']:.1f} / {eu['Rest']:.1f} |")

        lines.append(f"## {name}")
        lines.append("")
        lines.append("Evidence: " + ", ".join(f"{k}={v}" for k, v in ev.items()))
        lines.append("")
        lines.append("Pr(Mastery | evidence): " + ", ".join(f"{k} {pct(v)}" for k, v in r["mastery"].items()))
        lines.append("")
        lines.append("| Action | P(Pass) | P(Stress=Low) | P(Stress=Medium) | P(Stress=High) | EU |")
        lines.append("|---|---|---|---|---|---|")
        for action, joint in r["outcomes"].items():
            exam = marginal(joint, "ExamSuccess")
            stress = marginal(joint, "Stress")
            mark = " ✓" if action == r["best_action"] else ""
            lines.append(f"| {action}{mark} | {pct(exam['Pass'])} | {pct(stress['Low'])} | "
                         f"{pct(stress['Medium'])} | {pct(stress['High'])} | {eu[action]:.1f} |")
        lines.append("")
        lines.append(f"**Chosen action:** {ACTIONS[r['best_action']]['title']} "
                     f"({ACTIONS[r['best_action']]['description'].lower()})")
        lines.append("")

    text = "\n".join(lines[:4] + summary + [""] + lines[4:])
    print(text)
    out = os.path.join(ROOT, "docs", "week10_decision_results.md")
    with open(out, "w") as f:
        f.write(text + "\n")
    print("Saved", out)


if __name__ == "__main__":
    main()
