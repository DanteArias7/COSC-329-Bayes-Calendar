"""Week 11: simulate every student type over the 10 days before an exam and
write the schedules to docs/week11_schedules.md. Doesn't touch the calendar.

Run from the project root:
    python scripts/simulate_scenarios.py
"""
import os
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.decision import DecisionMaker
from src.scenarios import STUDENT_PROFILES
from src.scheduler import plan

# fixed dates so the results are the same every time
START = date(2026, 11, 23)
EXAM = date(2026, 12, 3)
ICON = {"Intense": "Intense (5h)", "Light": "Light (1h)", "Rest": "Rest"}


def table(days):
    rows = ["| Date | Days left | Practice score | Action | P(pass) | P(high stress) | EU (Intense / Light / Rest) |",
            "|---|---|---|---|---|---|---|"]
    for d in days:
        eu = d["expected_utility"]
        rows.append(f"| {d['date']:%a %b %d} | {d['days_left']} ({d['days_remaining']}) | {d['practice_score']} | "
                    f"**{ICON[d['action']]}** | {d['p_pass']:.0%} | {d['p_high_stress']:.0%} | "
                    f"{eu['Intense']:.1f} / {eu['Light']:.1f} / {eu['Rest']:.1f} |")
    return rows


def overview(results):
    dates = [d["date"] for d in next(iter(results.values()))]
    rows = ["| Student | " + " | ".join(f"{x:%b %d}" for x in dates) + " |",
            "|---|" + "---|" * len(dates)]
    for name, days in results.items():
        rows.append(f"| {STUDENT_PROFILES[name]['label']} | "
                    + " | ".join(d["action"] for d in days) + " |")
    return rows


def main():
    dm = DecisionMaker()
    static = {n: plan(p["evidence"], EXAM, START, dm) for n, p in STUDENT_PROFILES.items()}
    progress = {n: plan(p["evidence"], EXAM, START, dm, progress=True) for n, p in STUDENT_PROFILES.items()}

    lines = ["# Week 11 Simulated Schedules", "",
             f"Generated by `scripts/simulate_scenarios.py`. Exam on {EXAM:%a %b %d}, planning from {START:%a %b %d}.",
             "", "Student profiles (from `src/scenarios.py`):", ""]
    for p in STUDENT_PROFILES.values():
        lines.append(f"- **{p['label']}:** " + ", ".join(f"{k}={v}" for k, v in p["evidence"].items()))
    lines += ["", "## Fixed students", "",
              "Each student's evidence stays the same every day. Only DaysRemaining changes.", ""]
    lines += overview(static)
    lines += ["", "## With student progress (`--progress`)", "",
              "Studying raises the practice score (Intense +1 point, Light +0.5, every 2 points = one level up) "
              "and 3 rest days in a row lowers it by one level.", ""]
    lines += overview(progress)
    for name in STUDENT_PROFILES:
        lines += ["", f"### {STUDENT_PROFILES[name]['label']} (with progress)", ""]
        lines += table(progress[name])

    text = "\n".join(lines)
    print(text)
    out = os.path.join(ROOT, "docs", "week11_schedules.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write(text + "\n")
    print("Saved", out)


if __name__ == "__main__":
    main()
