"""Week 9: run test queries on a few example students and check the results
make sense. Also writes the output to docs/week9_inference_results.md.

Run from the project root:
    python scripts/test_inference.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.inference import Planner, marginal

STUDENTS = {
    "Struggling student, exam soon": {
        "Difficulty_A": "Hard", "Difficulty_B": "Hard", "Difficulty_C": "Medium",
        "PracticeScore": "Low", "DaysRemaining": "Few",
    },
    "Struggling student, lots of time": {
        "Difficulty_A": "Hard", "Difficulty_B": "Hard", "Difficulty_C": "Medium",
        "PracticeScore": "Low", "DaysRemaining": "Many",
    },
    "Average student": {
        "Difficulty_A": "Medium", "Difficulty_B": "Medium", "Difficulty_C": "Medium",
        "PracticeScore": "Medium", "DaysRemaining": "Some",
    },
    "Advanced student, exam soon": {
        "Difficulty_A": "Easy", "Difficulty_B": "Easy", "Difficulty_C": "Medium",
        "PracticeScore": "High", "DaysRemaining": "Few",
    },
}


def pct(x):
    return f"{x * 100:.1f}%"


def main():
    planner = Planner()
    lines = ["# Week 9 Inference Results", "",
             "Generated by `scripts/test_inference.py` using Variable Elimination.", ""]

    for name, ev in STUDENTS.items():
        lines.append(f"## {name}")
        lines.append("")
        lines.append("Evidence: " + ", ".join(f"{k}={v}" for k, v in ev.items()))
        lines.append("")

        m = planner.mastery(ev)
        lines.append("Pr(Mastery | evidence): " + ", ".join(f"{k} {pct(v)}" for k, v in m.items()))
        lines.append("")
        lines.append("| StudyPlan | P(Pass) | P(Stress=Low) | P(Stress=Medium) | P(Stress=High) |")
        lines.append("|---|---|---|---|---|")
        for action, joint in planner.outcomes_all_actions(ev).items():
            exam = marginal(joint, "ExamSuccess")
            stress = marginal(joint, "Stress")
            lines.append(f"| {action} | {pct(exam['Pass'])} | {pct(stress['Low'])} | "
                         f"{pct(stress['Medium'])} | {pct(stress['High'])} |")
        lines.append("")

    text = "\n".join(lines)
    print(text)
    out = os.path.join(ROOT, "docs", "week9_inference_results.md")
    with open(out, "w") as f:
        f.write(text + "\n")
    print("Saved", out)


if __name__ == "__main__":
    main()
